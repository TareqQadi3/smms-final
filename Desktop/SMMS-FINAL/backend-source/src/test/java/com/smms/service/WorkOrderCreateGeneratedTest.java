package com.smms.service;

import com.smms.entity.*;
import com.smms.enums.SubType;
import com.smms.enums.TicketPriority;
import com.smms.enums.TicketStatus;
import com.smms.enums.UserRole;
import com.smms.exception.PlanLimitExceededException;
import com.smms.exception.ResourceNotFoundException;
import com.smms.exception.WorkflowException;
import com.smms.mapper.WorkOrderMapper;
import com.smms.repository.*;
import com.smms.security.TenantSecurityService;
import com.smms.security.WorkOrderAccessPolicy;
import com.smms.workflow.GeneratedWorkOrderSpec;
import com.smms.workflow.WorkOrderHistoryWriter;
import jakarta.persistence.EntityManager;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;

import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

class WorkOrderCreateGeneratedTest {

    private WorkOrderRepository workOrderRepo;
    private TicketHistoryRepository historyRepo;
    private NotificationService notifications;
    private PlanEnforcementService plan;
    private EntityManager em;
    private ControlRoomRepository controlRooms;
    private AssetRepository assets;
    private WorkOrderService service;

    private final UUID tenant = UUID.randomUUID();
    private Center center;
    private ControlRoom room;
    private User requester;

    @BeforeEach
    void setUp() {
        workOrderRepo = mock(WorkOrderRepository.class);
        historyRepo = mock(TicketHistoryRepository.class);
        notifications = mock(NotificationService.class);
        plan = mock(PlanEnforcementService.class);
        em = mock(EntityManager.class);
        controlRooms = mock(ControlRoomRepository.class);
        assets = mock(AssetRepository.class);
        service = new WorkOrderService(workOrderRepo, historyRepo, new WorkflowEngine(), notifications,
            mock(WorkOrderMapper.class), plan, mock(TenantSecurityService.class), mock(WorkOrderAccessPolicy.class),
            em, mock(UserRepository.class), new WorkOrderHistoryWriter(historyRepo), controlRooms, assets);

        center = new Center();
        center.setId(UUID.randomUUID());
        center.setTenantId(tenant);
        room = new ControlRoom();
        room.setId(UUID.randomUUID());
        room.setTenantId(tenant);
        room.setCenter(center);
        requester = new User();
        requester.setId(UUID.randomUUID());
        requester.setTenantId(tenant);
        requester.setRole(UserRole.control_room);
        requester.setActive(true);

        when(controlRooms.findByIdAndTenantIdAndDeletedAtIsNull(room.getId(), tenant)).thenReturn(Optional.of(room));
        when(workOrderRepo.save(any(WorkOrder.class))).thenAnswer(i -> i.getArgument(0));
    }

    private GeneratedWorkOrderSpec spec(UUID assetId) {
        return new GeneratedWorkOrderSpec(tenant, room.getId(), SubType.electrical, TicketPriority.high,
            "PM: pump", "check <b>bearings</b>", "Level 2", assetId, requester, "Generated by plan X");
    }

    @Test
    void createsNewTicketInTheRequestersNameWithHistoryAndNotification() {
        Asset asset = Asset.builder().name("Pump").nameAr("p").build();
        asset.setId(UUID.randomUUID());
        asset.setTenantId(tenant);
        when(assets.findByIdAndTenantIdAndDeletedAtIsNull(asset.getId(), tenant)).thenReturn(Optional.of(asset));

        WorkOrder wo = service.createGenerated(spec(asset.getId()));

        assertThat(wo.getTenantId()).isEqualTo(tenant);
        assertThat(wo.getStatus()).isEqualTo(TicketStatus.NEW);
        assertThat(wo.getCurrentStage()).isEqualTo("new");
        assertThat(wo.getPriority()).isEqualTo(TicketPriority.high);
        assertThat(wo.getAsset()).isSameAs(asset);
        assertThat(wo.getCenter()).isSameAs(center);
        assertThat(wo.getControlRoom()).isSameAs(room);
        assertThat(wo.getRequestedBy()).isSameAs(requester);
        assertThat(wo.getCreatedByRole()).isEqualTo(UserRole.control_room);
        assertThat(wo.getDescription()).doesNotContain("<b>");

        InOrderChecks.verifyFlushRefreshHistoryNotify(workOrderRepo, em, historyRepo, notifications, wo);
        ArgumentCaptor<TicketHistory> h = ArgumentCaptor.forClass(TicketHistory.class);
        verify(historyRepo).save(h.capture());
        assertThat(h.getValue().getFromStatus()).isNull();
        assertThat(h.getValue().getToStatus()).isEqualTo(TicketStatus.NEW);
        assertThat(h.getValue().getNote()).isEqualTo("Generated by plan X");
        assertThat(h.getValue().getActor()).isSameAs(requester);
        verify(plan).checkTicketLimit(tenant);
    }

    @Test
    void assetIsOptionalAndPriorityDefaultsToMedium() {
        GeneratedWorkOrderSpec s = new GeneratedWorkOrderSpec(tenant, room.getId(), SubType.civil, null,
            "t", null, null, null, requester, null);
        WorkOrder wo = service.createGenerated(s);
        assertThat(wo.getAsset()).isNull();
        assertThat(wo.getPriority()).isEqualTo(TicketPriority.medium);
        verifyNoInteractions(assets);
        ArgumentCaptor<TicketHistory> h = ArgumentCaptor.forClass(TicketHistory.class);
        verify(historyRepo).save(h.capture());
        assertThat(h.getValue().getNote()).isEqualTo("Ticket created");
    }

    @Test
    void controlRoomOfAnotherTenantIsNotFoundAndNothingIsWritten() {
        UUID otherRoom = UUID.randomUUID();
        when(controlRooms.findByIdAndTenantIdAndDeletedAtIsNull(otherRoom, tenant)).thenReturn(Optional.empty());
        GeneratedWorkOrderSpec s = new GeneratedWorkOrderSpec(tenant, otherRoom, SubType.civil, null,
            "t", null, null, null, requester, null);
        assertThatThrownBy(() -> service.createGenerated(s)).isInstanceOf(ResourceNotFoundException.class);
        verify(workOrderRepo, never()).save(any());
        verifyNoInteractions(notifications);
    }

    @Test
    void assetOfAnotherTenantIsNotFound() {
        UUID foreign = UUID.randomUUID();
        when(assets.findByIdAndTenantIdAndDeletedAtIsNull(foreign, tenant)).thenReturn(Optional.empty());
        assertThatThrownBy(() -> service.createGenerated(spec(foreign))).isInstanceOf(ResourceNotFoundException.class);
        verify(workOrderRepo, never()).save(any());
    }

    @Test
    void requesterOfAnotherTenantIsRefused() {
        requester.setTenantId(UUID.randomUUID());
        assertThatThrownBy(() -> service.createGenerated(spec(null))).isInstanceOf(IllegalArgumentException.class);
        requester.setTenantId(null);
        assertThatThrownBy(() -> service.createGenerated(spec(null))).isInstanceOf(IllegalArgumentException.class);
        verify(workOrderRepo, never()).save(any());
    }

    @Test
    void inactiveOrDeletedRequesterIsRefused() {
        requester.setActive(false);
        assertThatThrownBy(() -> service.createGenerated(spec(null))).isInstanceOf(WorkflowException.class);
        requester.setActive(true);
        requester.setDeletedAt(java.time.Instant.now());
        assertThatThrownBy(() -> service.createGenerated(spec(null))).isInstanceOf(WorkflowException.class);
        verify(workOrderRepo, never()).save(any());
    }

    @Test
    void inactiveControlRoomIsRefused() {
        room.setActive(false);
        assertThatThrownBy(() -> service.createGenerated(spec(null))).isInstanceOf(WorkflowException.class);
    }

    @Test
    void missingTenantOrSubTypeIs400() {
        assertThatThrownBy(() -> service.createGenerated(new GeneratedWorkOrderSpec(null, room.getId(),
            SubType.civil, null, "t", null, null, null, requester, null)))
            .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> service.createGenerated(new GeneratedWorkOrderSpec(tenant, room.getId(),
            null, null, "t", null, null, null, requester, null)))
            .isInstanceOf(IllegalArgumentException.class);
    }

    @Test
    void planTicketLimitStopsCreation() {
        doThrow(new PlanLimitExceededException("limit")).when(plan).checkTicketLimit(tenant);
        assertThatThrownBy(() -> service.createGenerated(spec(null))).isInstanceOf(PlanLimitExceededException.class);
        verify(workOrderRepo, never()).save(any());
        verifyNoInteractions(notifications);
    }

    /** Verifies the order used by create(): save, flush, refresh, history, notify. */
    private static final class InOrderChecks {
        static void verifyFlushRefreshHistoryNotify(WorkOrderRepository repo, EntityManager em,
                                                    TicketHistoryRepository history, NotificationService n, WorkOrder wo) {
            var order = inOrder(repo, em, history, n);
            order.verify(repo).save(wo);
            order.verify(repo).flush();
            order.verify(em).refresh(wo);
            order.verify(history).save(any(TicketHistory.class));
            order.verify(n).notifyControlRoom(wo);
        }
    }
}
